-- CosMunity - notificacoes reais no PostgreSQL
-- Execute uma unica vez. Reexecucao segura: CREATE OR REPLACE e DROP TRIGGER IF EXISTS.
BEGIN;

CREATE TABLE IF NOT EXISTS notificacao (
  id_notificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_destinatario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_origem BIGINT REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  tipo VARCHAR(40) NOT NULL,
  titulo VARCHAR(160) NOT NULL,
  mensagem VARCHAR(500) NOT NULL,
  tela INTEGER NOT NULL,
  referencia_id BIGINT,
  criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  lida_em TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_notificacao_usuario_data
  ON notificacao (id_destinatario, criada_em DESC, id_notificacao DESC);
CREATE INDEX IF NOT EXISTS idx_notificacao_usuario_nao_lida
  ON notificacao (id_destinatario) WHERE lida_em IS NULL;

CREATE OR REPLACE FUNCTION cosmunity_notificar(
  destino BIGINT, origem BIGINT, categoria TEXT, assunto TEXT,
  corpo TEXT, destino_tela INTEGER, id_referencia BIGINT
) RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
  IF destino IS NULL OR destino = origem THEN RETURN; END IF;
  INSERT INTO notificacao(id_destinatario, id_origem, tipo, titulo, mensagem, tela, referencia_id)
  SELECT u.id_usuario, origem, left(categoria,40), left(assunto,160), left(corpo,500), destino_tela, id_referencia
  FROM usuario u
  WHERE u.id_usuario = destino AND u.ativo = true;
END; $$;

CREATE OR REPLACE FUNCTION cosmunity_gerar_notificacao()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  cliente BIGINT;
  artista BIGINT;
  autor BIGINT;
  nome_contexto TEXT;
  destino BIGINT;
  dono BIGINT;
  cid BIGINT;
  evento_nome TEXT;
BEGIN
  IF TG_TABLE_NAME = 'conversa' AND TG_OP = 'INSERT' THEN
    SELECT a.id_usuario INTO artista FROM artista a WHERE a.id_artista = NEW.id_artista;
    PERFORM cosmunity_notificar(artista, NEW.id_usuario, 'CONVERSA', 'Nova conversa',
      'Um usuário iniciou uma conversa com você.', 32, NEW.id_conversa);

  ELSIF TG_TABLE_NAME = 'mensagem_privada' AND TG_OP = 'INSERT' THEN
    SELECT c.id_usuario, a.id_usuario INTO cliente, artista
      FROM conversa c JOIN artista a ON a.id_artista = c.id_artista
      WHERE c.id_conversa = NEW.id_conversa;
    destino := CASE WHEN NEW.id_remetente = cliente THEN artista ELSE cliente END;
    SELECT u.nome INTO nome_contexto FROM usuario u WHERE u.id_usuario = NEW.id_remetente;
    PERFORM cosmunity_notificar(destino, NEW.id_remetente, 'MENSAGEM', 'Nova mensagem privada',
      coalesce(nome_contexto, 'Alguém') || ' enviou uma mensagem.', 32, NEW.id_conversa);

  ELSIF TG_TABLE_NAME = 'negociacao' AND TG_OP IN ('INSERT','UPDATE') THEN
    SELECT c.id_usuario, a.id_usuario INTO cliente, artista
      FROM conversa c JOIN artista a ON a.id_artista = c.id_artista
      WHERE c.id_conversa = NEW.id_conversa;
    IF TG_OP = 'INSERT' THEN
      PERFORM cosmunity_notificar(cliente, NULL, 'NEGOCIACAO', 'Negociação iniciada',
        'Uma negociação foi iniciada na sua conversa.', 33, NEW.id_conversa);
      PERFORM cosmunity_notificar(artista, NULL, 'NEGOCIACAO', 'Negociação iniciada',
        'Uma negociação foi iniciada na sua conversa.', 33, NEW.id_conversa);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
      PERFORM cosmunity_notificar(cliente, NULL, 'NEGOCIACAO', 'Status da negociação alterado',
        'Novo status: ' || replace(NEW.status, '_', ' ') || '.', 33, NEW.id_conversa);
      PERFORM cosmunity_notificar(artista, NULL, 'NEGOCIACAO', 'Status da negociação alterado',
        'Novo status: ' || replace(NEW.status, '_', ' ') || '.', 33, NEW.id_conversa);
    END IF;

  ELSIF TG_TABLE_NAME = 'avaliacao' AND TG_OP = 'INSERT' THEN
    PERFORM cosmunity_notificar(NEW.id_avaliado, NEW.id_avaliador, 'AVALIACAO', 'Você recebeu uma avaliação',
      'Alguém avaliou a experiência de negociação com você.', 50, NULL);

  ELSIF TG_TABLE_NAME = 'membro_comunidade' AND TG_OP IN ('INSERT','UPDATE') THEN
    IF TG_OP = 'INSERT' OR (OLD.ativo = false AND NEW.ativo = true) THEN
      SELECT c.id_criador, c.nome INTO dono, nome_contexto FROM comunidade c WHERE c.id_comunidade = NEW.id_comunidade;
      PERFORM cosmunity_notificar(dono, NEW.id_usuario, 'COMUNIDADE', 'Novo integrante na comunidade',
        'Uma pessoa entrou em ' || coalesce(nome_contexto, 'sua comunidade') || '.', 39, NEW.id_comunidade);
    ELSIF OLD.ativo = true AND NEW.ativo = false THEN
      PERFORM cosmunity_notificar(NEW.id_usuario, NULL, 'COMUNIDADE', 'Participação encerrada',
        'Sua participação em uma comunidade foi encerrada.', 38, NULL);
    END IF;

  ELSIF TG_TABLE_NAME = 'mensagem_comunidade' AND TG_OP = 'INSERT' THEN
    SELECT c.nome INTO nome_contexto FROM comunidade c WHERE c.id_comunidade = NEW.id_comunidade;
    INSERT INTO notificacao(id_destinatario, id_origem, tipo, titulo, mensagem, tela, referencia_id)
    SELECT mc.id_usuario, NEW.id_usuario, 'COMUNIDADE', 'Nova mensagem em comunidade',
      'Nova mensagem em ' || coalesce(nome_contexto,'uma comunidade') || '.', 40, NEW.id_comunidade
    FROM membro_comunidade mc
    JOIN usuario u ON u.id_usuario = mc.id_usuario AND u.ativo = true
    WHERE mc.id_comunidade = NEW.id_comunidade AND mc.ativo = true
      AND mc.id_usuario <> NEW.id_usuario;

  ELSIF TG_TABLE_NAME = 'evento_interesse' AND TG_OP = 'INSERT' THEN
    SELECT e.id_organizador, e.titulo INTO dono, evento_nome
      FROM evento e WHERE e.id_evento = NEW.id_evento;
    PERFORM cosmunity_notificar(dono, NEW.id_usuario, 'EVENTO', 'Novo interessado no evento',
      'Uma pessoa demonstrou interesse em ' || coalesce(evento_nome,'seu evento') || '.', 47, NEW.id_evento);

  ELSIF TG_TABLE_NAME = 'evento' AND TG_OP = 'UPDATE' THEN
    IF ROW(NEW.titulo,NEW.data_inicio,NEW.data_fim,NEW.cidade,NEW.estado,NEW.local_evento)
       IS DISTINCT FROM ROW(OLD.titulo,OLD.data_inicio,OLD.data_fim,OLD.cidade,OLD.estado,OLD.local_evento) THEN
      INSERT INTO notificacao(id_destinatario,id_origem,tipo,titulo,mensagem,tela,referencia_id)
      SELECT ei.id_usuario, NEW.id_organizador, 'EVENTO', 'Evento atualizado',
        'Houve alterações em ' || left(NEW.titulo,150) || '.', 47, NEW.id_evento
      FROM evento_interesse ei JOIN usuario u ON u.id_usuario = ei.id_usuario AND u.ativo = true
      WHERE ei.id_evento = NEW.id_evento AND ei.id_usuario <> NEW.id_organizador;
    END IF;
  ELSIF TG_TABLE_NAME = 'evento' AND TG_OP = 'DELETE' THEN
    INSERT INTO notificacao(id_destinatario,id_origem,tipo,titulo,mensagem,tela,referencia_id)
    SELECT ei.id_usuario, OLD.id_organizador, 'EVENTO', 'Evento cancelado',
      'O evento ' || left(OLD.titulo,150) || ' foi excluído.', 46, NULL
    FROM evento_interesse ei JOIN usuario u ON u.id_usuario = ei.id_usuario AND u.ativo = true
    WHERE ei.id_evento = OLD.id_evento AND ei.id_usuario <> OLD.id_organizador;

  ELSIF TG_TABLE_NAME = 'artista' AND TG_OP = 'UPDATE' THEN
    IF NEW.ativo = true AND OLD.ativo = false THEN
      PERFORM cosmunity_notificar(NEW.id_usuario, NULL, 'CONTA', 'Perfil artístico ativado',
        'Seu perfil de artista está ativo no CosMunity.', 21, NULL);
    END IF;

  ELSIF TG_TABLE_NAME = 'usuario' AND TG_OP = 'UPDATE' THEN
    IF NEW.senha_hash IS DISTINCT FROM OLD.senha_hash THEN
      PERFORM cosmunity_notificar(NEW.id_usuario, NULL, 'SEGURANCA', 'Senha alterada',
        'A senha da sua conta foi modificada. Se não foi você, procure suporte.', 52, NULL);
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS tg_notif_conversa ON conversa;
CREATE TRIGGER tg_notif_conversa AFTER INSERT ON conversa FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_mensagem_privada ON mensagem_privada;
CREATE TRIGGER tg_notif_mensagem_privada AFTER INSERT ON mensagem_privada FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_negociacao ON negociacao;
CREATE TRIGGER tg_notif_negociacao AFTER INSERT OR UPDATE ON negociacao FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_avaliacao ON avaliacao;
CREATE TRIGGER tg_notif_avaliacao AFTER INSERT ON avaliacao FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_membro ON membro_comunidade;
CREATE TRIGGER tg_notif_membro AFTER INSERT OR UPDATE ON membro_comunidade FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_mensagem_comunidade ON mensagem_comunidade;
CREATE TRIGGER tg_notif_mensagem_comunidade AFTER INSERT ON mensagem_comunidade FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_interesse ON evento_interesse;
CREATE TRIGGER tg_notif_interesse AFTER INSERT ON evento_interesse FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_evento ON evento;
DROP TRIGGER IF EXISTS tg_notif_evento_delete ON evento;
CREATE TRIGGER tg_notif_evento AFTER UPDATE ON evento FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
CREATE TRIGGER tg_notif_evento_delete BEFORE DELETE ON evento FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_artista ON artista;
CREATE TRIGGER tg_notif_artista AFTER UPDATE ON artista FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
DROP TRIGGER IF EXISTS tg_notif_usuario ON usuario;
CREATE TRIGGER tg_notif_usuario AFTER UPDATE ON usuario FOR EACH ROW EXECUTE FUNCTION cosmunity_gerar_notificacao();
COMMIT;